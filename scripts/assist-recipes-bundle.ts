/**
 * Writes the VCFO Assist extension's bundled recipes from Suite's registry, signed with the DEV key
 * (mock hosts only). Suite's `src/lib/assist-agents/recipes/*.json` is the single source; the
 * extension's copy is this file's output and nothing else.
 *
 *   node --conditions=react-server --import tsx scripts/assist-recipes-bundle.ts
 *
 * Run it after any recipe edit (and bump the recipe's version). `src/lib/assist-agents/recipe.test.ts`
 * fails while the two differ. The signature is deterministic (Ed25519), so a rerun with no recipe
 * change writes the same bytes.
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { listRecipes } from '@/lib/assist-agents/registry';
import { devRecipeSigner, rawPublicKey, signRecipe } from '@/lib/assist-agents/signing';

export const BUNDLE_PATH = path.resolve(process.cwd(), 'extensions/vcfo-assist/src/recipes/bundled.json');

// No env: always the dev key, whatever this shell has in ASSIST_RECIPE_PRIVATE_KEY.
const recipes = Object.fromEntries(listRecipes().map((recipe) => [recipe.id, signRecipe(recipe, {})]));
const bundle = {
  note: 'GENERATED by scripts/assist-recipes-bundle.ts from src/lib/assist-agents/recipes. Do not edit. Signed with the dev key: valid on mock hosts only.',
  devPublicKey: rawPublicKey(devRecipeSigner().publicKey),
  recipes,
};
writeFileSync(BUNDLE_PATH, `${JSON.stringify(bundle, null, 2)}\n`);
console.log(`wrote ${Object.keys(recipes).join(', ')} to ${path.relative(process.cwd(), BUNDLE_PATH)}`);
